-- =====================================================================
-- SuperMart Chain | COSC 3380 HW2 Phase 1 | schema.sql
-- PostgreSQL. Run on an EMPTY database (dropdb/createdb to reset).
-- Supermarket tables live in schema "public".
-- Bank tables live in a SEPARATE schema "bank" (assignment: the bank is
-- NOT the same database as the store). Nothing in public has a foreign
-- key into bank, because a real store never owns the bank's tables.
-- =====================================================================

CREATE SCHEMA IF NOT EXISTS bank;

-- ---------- Reference / lookup tables (public) -----------------------

CREATE TABLE IF NOT EXISTS tax_rules (
    state     CHAR(2) PRIMARY KEY,
    tax_rate  NUMERIC(6,4) NOT NULL CHECK (tax_rate >= 0 AND tax_rate < 1)
);

CREATE TABLE IF NOT EXISTS stores (
    store_id    INTEGER PRIMARY KEY,
    store_name  VARCHAR(100) NOT NULL,
    city        VARCHAR(100) NOT NULL,
    state       CHAR(2)      NOT NULL REFERENCES tax_rules(state),
    address     VARCHAR(200) NOT NULL
);

CREATE TABLE IF NOT EXISTS aisles (
    aisle_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id      INTEGER NOT NULL REFERENCES stores(store_id) ON DELETE CASCADE,
    aisle_number  INTEGER NOT NULL CHECK (aisle_number > 0),
    aisle_name    VARCHAR(100) NOT NULL,
    UNIQUE (store_id, aisle_number),
    UNIQUE (aisle_id, store_id)          -- target for inventory's composite FK
);

CREATE TABLE IF NOT EXISTS products (
    product_id      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sku             VARCHAR(30)  NOT NULL UNIQUE,
    product_name    VARCHAR(100) NOT NULL,
    category        VARCHAR(50)  NOT NULL,
    unit_price      NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0),
    unit            VARCHAR(20)  NOT NULL,
    tax_exempt      BOOLEAN NOT NULL DEFAULT FALSE,
    -- derived flag: items sold per pound are priced by weight
    sold_by_weight  BOOLEAN GENERATED ALWAYS AS (unit = 'lb') STORED
);

-- Composite key #1: one stock row per (store, product).
-- The composite FK (aisle_id, store_id) guarantees the aisle really
-- belongs to the SAME store as the inventory row.
CREATE TABLE IF NOT EXISTS inventory (
    store_id        INTEGER NOT NULL REFERENCES stores(store_id)     ON DELETE CASCADE,
    product_id      INTEGER NOT NULL REFERENCES products(product_id) ON DELETE CASCADE,
    aisle_id        INTEGER,
    stock_quantity  NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
    PRIMARY KEY (store_id, product_id),
    FOREIGN KEY (aisle_id, store_id) REFERENCES aisles(aisle_id, store_id)
);

CREATE TABLE IF NOT EXISTS customers (
    customer_id    INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_name  VARCHAR(100) NOT NULL,
    email          VARCHAR(150) UNIQUE,
    created_at     TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------- Bank (separate schema) -----------------------------------

CREATE TABLE IF NOT EXISTS bank.bank_accounts (
    account_id   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    holder_name  VARCHAR(100) NOT NULL,
    balance      NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (balance >= 0),
    opened_at    TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Bank-side ledger: one row for every debit/credit of an account.
CREATE TABLE IF NOT EXISTS bank.bank_transactions (
    tx_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id    INTEGER NOT NULL REFERENCES bank.bank_accounts(account_id) ON DELETE CASCADE,
    amount        NUMERIC(12,2) NOT NULL CHECK (amount > 0),
    tx_type       VARCHAR(10) NOT NULL CHECK (tx_type IN ('WITHDRAWAL','DEPOSIT')),
    reference     VARCHAR(60),
    tx_timestamp  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------- Transaction tables (public) ------------------------------

CREATE TABLE IF NOT EXISTS sales (
    sale_id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    store_id        INTEGER NOT NULL REFERENCES stores(store_id),
    customer_id     INTEGER REFERENCES customers(customer_id) ON DELETE SET NULL,
    subtotal        NUMERIC(12,2) NOT NULL CHECK (subtotal >= 0),
    tax_total       NUMERIC(12,2) NOT NULL CHECK (tax_total >= 0),
    total           NUMERIC(12,2) NOT NULL CHECK (total >= 0),
    payment_method  VARCHAR(10)   NOT NULL CHECK (payment_method IN ('CARD','CASH')),
    created_at      TIMESTAMPTZ   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK (total = subtotal + tax_total)
);

-- Composite key #2: receipt line = (sale, line number).
CREATE TABLE IF NOT EXISTS sale_items (
    sale_id      INTEGER NOT NULL REFERENCES sales(sale_id) ON DELETE CASCADE,
    line_number  INTEGER NOT NULL CHECK (line_number > 0),
    product_id   INTEGER NOT NULL REFERENCES products(product_id),
    quantity     NUMERIC(10,2) NOT NULL CHECK (quantity > 0),   -- units OR pounds
    unit_price   NUMERIC(10,2) NOT NULL CHECK (unit_price >= 0), -- price snapshot
    subtotal     NUMERIC(12,2) NOT NULL CHECK (subtotal >= 0),
    tax          NUMERIC(12,2) NOT NULL CHECK (tax >= 0),
    line_total   NUMERIC(12,2) NOT NULL CHECK (line_total >= 0),
    PRIMARY KEY (sale_id, line_number),
    CHECK (line_total = subtotal + tax)
);

-- One payment per sale (no split checks). bank_account_id is only a
-- reference to the bank's account number: deliberately NO foreign key,
-- because the bank is a separate system.
CREATE TABLE IF NOT EXISTS payments (
    payment_id       INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id          INTEGER NOT NULL UNIQUE REFERENCES sales(sale_id) ON DELETE CASCADE,
    method           VARCHAR(10) NOT NULL CHECK (method IN ('CARD','CASH')),
    amount           NUMERIC(12,2) NOT NULL CHECK (amount >= 0),
    bank_account_id  INTEGER,
    status           VARCHAR(20) NOT NULL DEFAULT 'SUCCESS'
                     CHECK (status IN ('SUCCESS','FAILED','REFUNDED')),
    paid_at          TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CHECK ( (method = 'CARD' AND bank_account_id IS NOT NULL)
         OR (method = 'CASH' AND bank_account_id IS NULL) )
);

-- ---------- Indexes (PK/UNIQUE columns are already indexed) ----------

CREATE INDEX IF NOT EXISTS idx_stores_state        ON stores(state);
CREATE INDEX IF NOT EXISTS idx_products_category   ON products(category);
CREATE INDEX IF NOT EXISTS idx_inventory_product   ON inventory(product_id);
CREATE INDEX IF NOT EXISTS idx_inventory_stock     ON inventory(stock_quantity);
CREATE INDEX IF NOT EXISTS idx_sales_store_time    ON sales(store_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_sales_customer      ON sales(customer_id);
CREATE INDEX IF NOT EXISTS idx_sale_items_product  ON sale_items(product_id);
CREATE INDEX IF NOT EXISTS idx_payments_account    ON payments(bank_account_id);
CREATE INDEX IF NOT EXISTS idx_bank_tx_account     ON bank.bank_transactions(account_id, tx_timestamp DESC);
